'use server';

import { fetchAuthorFeed, type AuthorFeedItem } from '@/lib/sanity';

/**
 * Поиск и фильтр в ленте участника.
 *
 * Действием, а не параметром в адресе, по одной причине: страница участника
 * статическая и пересобирается раз в час. Стоит ей начать читать search
 * params — и каждый заход робота считается отдельной сборкой, а мы только что
 * разбирались, почему счёт Vercel растёт от пересборок, а не от людей.
 *
 * Первая страница без фильтров приходит в HTML с сервера, поэтому робот
 * видит материалы и без единой строки скрипта. Действие вызывается уже
 * читателем, когда он что-то ищет.
 */
// Действие открыто для прямого POST, как и любое другое. Проверки прав тут
// нет намеренно: отдаётся ровно то, что и так лежит на странице в открытом
// виде. Запрос уходит в GROQ параметром, а не склейкой строк, тип ограничен
// перечислением, длина выборки прижата — подставить сюда чужой запрос нельзя.
export async function loadAuthorFeed(
  slug: string,
  locale: string,
  type: 'article' | 'news' | 'all',
  q: string,
  offset: number,
  limit: number,
): Promise<{ items: AuthorFeedItem[]; total: number }> {
  // Запрос режется до разумной длины: дальше он всё равно ничего не найдёт,
  // а в GROQ уходит как есть.
  const query = q.trim().slice(0, 80);
  return fetchAuthorFeed(
    slug,
    locale,
    Math.min(Math.max(limit, 1), 40),
    Math.max(offset, 0),
    type === 'all' ? undefined : type,
    query || undefined,
  );
}
